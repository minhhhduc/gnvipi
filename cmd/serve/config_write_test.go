func testProvider() []config.OpenAICompatibility {
	return []config.OpenAICompatibility{{
		Name:          "vendor",
		BaseURL:       "https://up.invalid/v1",
		APIKeyEntries: []config.OpenAICompatibilityAPIKey{{APIKey: "k"}},
		Models: []config.OpenAICompatibilityModel{{
			Name: "m", Alias: "vendor/m", DisplayName: "vendor/m",
		}},
	}}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

func TestRewriteConfigYAMLGolden(t *testing.T) {
	path := filepath.Join(t.TempDir(), "config.yaml")
	if err := rewriteConfigYAML(path, testProvider()); err != nil {
		t.Fatal(err)
	}
	const want = `# generated by cmd/serve; not used for API keys
openai-compatibility:
  - name: vendor
    base-url: https://up.invalid/v1
    api-key-entries:
      - api-key: k
    models:
      - name: m
        alias: vendor/m
        display-name: vendor/m
`
	if got := readFile(t, path); got != want {
		t.Fatalf("config =\n%s\nwant\n%s", got, want)
	}
}

