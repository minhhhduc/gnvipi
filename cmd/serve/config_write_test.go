func TestRewriteConfigYAMLQuotesSpecialValues(t *testing.T) {
	// Characters that break hand-concatenated YAML, including a value that
	// tries to open a new top-level key.
	const (
		name  = "vendor: #not-a-comment"
		url   = "https://up.invalid/v1 #frag"
		key   = "sk-\"quoted\":#\n inyected: true"
		model = "m: #\n\"q"
	)
	path := filepath.Join(t.TempDir(), "config.yaml")
	err := rewriteConfigYAML(path, []config.OpenAICompatibility{{
		Name:          name,
		BaseURL:       url,
		APIKeyEntries: []config.OpenAICompatibilityAPIKey{{APIKey: key}},
		Models:        []config.OpenAICompatibilityModel{{Name: model, Alias: "a"}},
	}})
	if err != nil {
		t.Fatal(err)
	}
	raw := readFile(t, path)

	var top map[string]any
	if err := yaml.Unmarshal([]byte(raw), &top); err != nil {
		t.Fatalf("generated YAML does not parse: %v\n%s", err, raw)
	}
	if len(top) != 1 {
		t.Fatalf("generated YAML has extra keys: %v\n%s", top, raw)
	}
	var doc struct {
		Providers []config.OpenAICompatibility `yaml:"openai-compatibility"`
	}
	if err := yaml.Unmarshal([]byte(raw), &doc); err != nil {
		t.Fatalf("unmarshal: %v\n%s", err, raw)
	}
	if len(doc.Providers) != 1 {
		t.Fatalf("providers = %d, want 1\n%s", len(doc.Providers), raw)
	}
	p := doc.Providers[0]
	if p.Name != name || p.BaseURL != url {
		t.Fatalf("provider = %#v", p)
	}
	if len(p.APIKeyEntries) != 1 || p.APIKeyEntries[0].APIKey != key {
		t.Fatalf("api keys = %#v", p.APIKeyEntries)
	}
	if len(p.Models) != 1 || p.Models[0].Name != model {
		t.Fatalf("models = %#v", p.Models)
	}
}

func TestAtomicWriteFileReplacesContent(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "file")
	if err := os.WriteFile(path, []byte("old"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := atomicWriteFile(path, []byte("new"), 0o600); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, path); got != "new" {
		t.Fatalf("content = %q, want %q", got, "new")
	}
	if entries, err := os.ReadDir(dir); err != nil || len(entries) != 1 {
		t.Fatalf("temp file left behind: %v, %v", entries, err)
	}
	if runtime.GOOS != "windows" {
		info, err := os.Stat(path)
		if err != nil {
			t.Fatal(err)
		}
		if got := info.Mode().Perm(); got != 0o600 {
			t.Fatalf("perm = %v, want 0600", got)
		}
	}
}

func TestAtomicWriteFileFailureKeepsDestination(t *testing.T) {
	// A non-empty directory at the destination makes the final rename fail on
	// every supported OS, standing in for a write interrupted before it.
	dir := t.TempDir()
	target := filepath.Join(dir, "config.yaml")
	old := filepath.Join(target, "old")
	if err := os.MkdirAll(target, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(old, []byte("old"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := atomicWriteFile(target, []byte("new"), 0o600); err == nil {
		t.Fatal("atomicWriteFile replaced a directory")
	}
	if got := readFile(t, old); got != "old" {
		t.Fatalf("previous content = %q, want %q", got, "old")
	}
	if entries, err := os.ReadDir(dir); err != nil || len(entries) != 1 {
		t.Fatalf("temp file left behind: %v, %v", entries, err)
	}
}

func TestAdminProvidersRejectsControlCharacters(t *testing.T) {
	old := prefs
	defer func() { prefs = old }()
	path := filepath.Join(t.TempDir(), "models.json")
	prefs = &modelPrefs{path: path}
	gin.SetMode(gin.TestMode)

	body := `[{"name":"evil\nmodels: []","base_url":"https://up.invalid/v1","model":"m"}]`
	w := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(w)
	c.Request = httptest.NewRequestWithContext(t.Context(), http.MethodPost, "/admin/providers", strings.NewReader(body))
	c.Request.Header.Set("Content-Type", "application/json")
	adminRoutes(c, nil, func() []gatewayModel { return nil })

	if w.Code != http.StatusBadRequest {
		t.Fatalf("status = %d, want 400: %s", w.Code, w.Body.String())
	}
	if !strings.Contains(w.Body.String(), "control characters") {
		t.Fatalf("body = %s", w.Body.String())
	}
	if len(prefs.providers) != 0 {
		t.Fatalf("providers changed: %#v", prefs.providers)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("mask file was written: %v", err)
	}
}
