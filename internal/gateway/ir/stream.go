package ir

// EventType enumerates the normalized stream events of one generation.
// Sequences follow the ordering contract documented on the package: one
// message_start, zero or more block groups, an optional usage_update, then
// exactly one terminal event (message_stop or error).
type EventType string

const (
	EventMessageStart EventType = "message_start"
	EventBlockStart   EventType = "block_start"
	EventBlockDelta   EventType = "block_delta"
	EventBlockStop    EventType = "block_stop"
	EventUsageUpdate  EventType = "usage_update"
	EventMessageStop  EventType = "message_stop"
	EventError        EventType = "error"
)

// DeltaType selects which kind of partial content a Delta carries.
type DeltaType string

const (
	// DeltaText is an incremental text fragment (the "content" delta of
	// all three protocols).
	DeltaText DeltaType = "text_delta"
	// DeltaToolArguments is a partial fragment of a tool call's JSON
	// arguments; the fragments concatenate in order and must be appended
	// without parsing, since upstreams split JSON mid-token.
	DeltaToolArguments DeltaType = "tool_arguments_delta"
	// DeltaReasoning is an incremental reasoning/thinking fragment.
	DeltaReasoning DeltaType = "reasoning_delta"
)

// Delta is one incremental content update. ToolCallID and ToolCallName
// identify the tool call the fragment belongs to; the name appears on the
// first fragment of a call and may be empty afterwards.
type Delta struct {
	Type         DeltaType `json:"type"`
	Text         string    `json:"text,omitempty"`
	PartialJSON  string    `json:"partial_json,omitempty"`
	ToolCallID   string    `json:"tool_call_id,omitempty"`
	ToolCallName string    `json:"tool_call_name,omitempty"`
}

// StreamError is the protocol-neutral payload of an error event. Kind uses
// the same normalized kind strings as internal/gateway/gwerr
// ("invalid_request", "rate_limit", ...); it stays a plain string here so
// the IR package does not import gwerr.
type StreamError struct {
	Kind    string `json:"kind,omitempty"`
	Message string `json:"message"`
}

// StreamEvent is one normalized event in a streaming generation. Index
// references the Block.Index of the block a block_start, block_delta or
// block_stop applies to. Message is set on message_start and carries the
// ID, role and model of the message the stream opens, plus any initial
// content; Block is set on block_start as a prototype
// (type plus, for tool_use, the tool call ID and name); Usage is set on
// message_start and usage_update; StopReason is set on message_stop; Error
// is set on error events.
type StreamEvent struct {
	Type       EventType    `json:"type"`
	Index      int          `json:"index,omitempty"`
	Message    *Message     `json:"message,omitempty"`
	Block      *Block       `json:"block,omitempty"`
	Delta      *Delta       `json:"delta,omitempty"`
	Usage      *Usage       `json:"usage,omitempty"`
	StopReason StopReason   `json:"stop_reason,omitempty"`
	Error      *StreamError `json:"error,omitempty"`
}

// NewMessageStart builds the opening event of a stream. ID is the message
// identifier the inbound protocol echoes on message_start /
// response.created; Model is the model the stream is being generated by.
func NewMessageStart(id string, role Role, model string, usage Usage) StreamEvent {
	return StreamEvent{
		Type:    EventMessageStart,
		Message: &Message{ID: id, Role: role, Model: model},
		Usage:   &usage,
	}
}

// NewBlockStart builds the event opening the block with the given index.
// The block prototype carries the block type and, for tool_use, the tool
// call ID and name.
func NewBlockStart(index int, prototype Block) StreamEvent {
	return StreamEvent{Type: EventBlockStart, Index: index, Block: &prototype}
}

// NewTextDelta builds a text delta event for the block with the given index.
func NewTextDelta(index int, text string) StreamEvent {
	return StreamEvent{
		Type:  EventBlockDelta,
		Index: index,
		Delta: &Delta{Type: DeltaText, Text: text},
	}
}

// NewToolArgumentsDelta builds a partial tool-arguments event for the block
// with the given index.
func NewToolArgumentsDelta(index int, toolCallID, fragment string) StreamEvent {
	return StreamEvent{
		Type:  EventBlockDelta,
		Index: index,
		Delta: &Delta{Type: DeltaToolArguments, PartialJSON: fragment, ToolCallID: toolCallID},
	}
}

// NewReasoningDelta builds a reasoning delta event for the block with the
// given index.
func NewReasoningDelta(index int, text string) StreamEvent {
	return StreamEvent{
		Type:  EventBlockDelta,
		Index: index,
		Delta: &Delta{Type: DeltaReasoning, Text: text},
	}
}

// NewBlockStop builds the event closing the block with the given index.
func NewBlockStop(index int) StreamEvent {
	return StreamEvent{Type: EventBlockStop, Index: index}
}

// NewUsageUpdate builds a usage_update event.
func NewUsageUpdate(usage Usage) StreamEvent {
	return StreamEvent{Type: EventUsageUpdate, Usage: &usage}
}

// NewMessageStop builds the terminal event carrying the stop reason.
func NewMessageStop(reason StopReason) StreamEvent {
	return StreamEvent{Type: EventMessageStop, StopReason: reason}
}

// NewErrorEvent builds a terminal error event.
func NewErrorEvent(kind, message string) StreamEvent {
	return StreamEvent{Type: EventError, Error: &StreamError{Kind: kind, Message: message}}
}
